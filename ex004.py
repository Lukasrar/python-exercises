firstVal = input("Enter the first value: ")

print(f'You entered: {firstVal} which is of type {type(firstVal)}')
print(f'is the value numeric? {firstVal.isnumeric()}')
print(f'is the value alphabetic? {firstVal.isalpha()}')
print(f'is the value alphanum? {firstVal.isalnum()}')
print(f'is the value upper? {firstVal.isupper()}')